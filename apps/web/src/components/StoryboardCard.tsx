import React from "react";
import { Bot, Plus, MoreHorizontal, Clock, Film } from "lucide-react";
import { Panel, Button, Pill } from "./Common.js";
import { Storyboard, Scene } from "@motionforge/core";

export function StoryboardCard({
  storyboard,
  onAddScene,
  onEditWithAgent,
  onEditScene,
  onApprove,
}: {
  storyboard: Storyboard | null;
  onAddScene: () => void;
  onEditWithAgent: () => void;
  onEditScene: (scene: Scene) => void;
  onApprove?: () => void;
}) {
  const scenes = storyboard?.scenes || [];
  const totalDuration = storyboard?.totalDuration || scenes.reduce((acc, s) => acc + s.duration, 0);

  return (
    <Panel
      title="3. Storyboard"
      subtitle="Generated by AI agent based on brief & selected style"
      headerRight={
        <div className="flex items-center gap-2">
          {storyboard && !storyboard.approved && onApprove && (
            <Button
              variant="secondary"
              size="sm"
              onClick={onApprove}
              className="text-xs border-success/40 text-success hover:bg-success-bg"
            >
              Approve Storyboard
            </Button>
          )}
          <Button
            variant="secondary"
            size="sm"
            icon={<Bot className="w-3.5 h-3.5 text-primary" />}
            onClick={onEditWithAgent}
          >
            Edit with Agent
          </Button>
        </div>
      }
      className="flex-1 min-w-[420px] gap-3"
    >
      {/* Scene Rows List */}
      <div className="flex flex-col gap-2.5 overflow-y-auto max-h-[540px] pr-1">
        {scenes.map((scene) => (
          <div
            key={scene.id}
            onClick={() => onEditScene(scene)}
            className="flex items-center justify-between p-3 rounded-lg bg-panel-2 border border-border hover:border-border-strong hover:bg-hover transition-colors cursor-pointer group"
          >
            {/* Left: Thumbnail & details */}
            <div className="flex items-center gap-3.5 overflow-hidden">
              {/* 120x72 Thumbnail */}
              <div className="w-[120px] min-w-[120px] h-[72px] rounded bg-app border border-border overflow-hidden flex items-center justify-center relative">
                {scene.stillFrameUrl ? (
                  <img
                    src={scene.stillFrameUrl}
                    alt={scene.title}
                    className="w-full h-full object-cover"
                  />
                ) : (
                  <div className="w-full h-full flex flex-col items-center justify-center bg-gradient-to-br from-panel-2 to-app text-text-faint p-2">
                    <Film className="w-5 h-5 text-text-dim mb-1" />
                    <span className="text-[10px] font-mono text-center truncate w-full">
                      Scene {scene.index}
                    </span>
                  </div>
                )}
                {/* Duration overlay badge */}
                <span className="absolute bottom-1 right-1 px-1.5 py-0.5 rounded bg-black/70 text-[9px] font-mono text-text">
                  {scene.duration}s
                </span>
              </div>

              {/* Title & description */}
              <div className="flex flex-col gap-1 overflow-hidden pr-2">
                <span className="text-sm font-semibold text-text tracking-tight group-hover:text-primary-soft transition-colors">
                  {scene.title}
                </span>
                <p className="text-xs text-text-dim line-clamp-2 leading-relaxed">
                  {scene.description}
                </p>
                {scene.voiceoverLine && (
                  <p className="text-[11px] text-text-faint italic truncate">
                    &ldquo;{scene.voiceoverLine}&rdquo;
                  </p>
                )}
              </div>
            </div>

            {/* Right: Chips & Menu */}
            <div className="flex items-center gap-2">
              <div className="hidden sm:flex flex-col items-end gap-1">
                <span className="px-2 py-0.5 rounded-full text-[10.5px] bg-panel border border-border text-text-dim">
                  {scene.mediaType || "Image + Video"}
                </span>
                <span className="px-2 py-0.5 rounded-full text-[10.5px] bg-primary-bg border border-primary/30 text-primary-soft">
                  {scene.styleTag || "Style: Cinematic"}
                </span>
              </div>

              <button
                onClick={(e) => {
                  e.stopPropagation();
                  onEditScene(scene);
                }}
                className="w-8 h-8 rounded-lg flex items-center justify-center text-text-dim hover:text-text hover:bg-panel transition-colors"
              >
                <MoreHorizontal className="w-4 h-4" />
              </button>
            </div>
          </div>
        ))}
      </div>

      {/* Footer controls: Add scene & Total Duration */}
      <div className="flex items-center justify-between pt-2 border-t border-border mt-auto">
        <Button
          variant="secondary"
          size="sm"
          icon={<Plus className="w-3.5 h-3.5" />}
          onClick={onAddScene}
        >
          Add Scene
        </Button>

        <div className="flex items-center gap-1.5 text-xs text-text-dim font-medium">
          <Clock className="w-3.5 h-3.5 text-text-faint" />
          <span>Total Duration:</span>
          <span className="text-text font-semibold">{totalDuration}s</span>
        </div>
      </div>
    </Panel>
  );
}
